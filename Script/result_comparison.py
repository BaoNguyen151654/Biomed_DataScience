import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
import plotly.express as px
import plotly.graph_objects as go
from plotly.subplots import make_subplots

# Regression - Overall
overall_cyto_claude = pd.read_csv('overallresult_claude_cyto_Viability.csv')
overall_cyto_gpt6 = pd.read_csv('overallresult_gpt6_cyto_Viability.csv')
overall_cyto_grok = pd.read_csv('overallresult_grok_cyto_Viability.csv')
overall_cyto_ml = pd.read_csv('overallresult_ml_cyto_viability.csv')
overall_cyto_ptfm = pd.read_csv('overallresult_ptfm_Viability.csv')
# Regression - Quantile
quantile_cyto_claude = pd.read_csv('quantileresult_claude_cyto_Viability.csv')
quantile_cyto_gpt6 = pd.read_csv('quantileresult_gpt6_cyto_Viability.csv')
quantile_cyto_grok = pd.read_csv('quantileresult_grok_cyto_Viability.csv')
quantile_cyto_ml = pd.read_csv('quantileresult_ml_cyto_viability.csv')
quantile_cyto_ptfm = pd.read_csv('quantileresult_ptfm_Viability.csv')
# Binary
binary_cyto_claude = pd.read_csv('evaluation_claude_cyto_binary.csv')
binary_cyto_gpt6 = pd.read_csv('evaluation_gpt_cyto_binary.csv')
binary_cyto_grok = pd.read_csv('evaluation_grok_cyto_binary.csv')
binary_cyto_ml = pd.read_csv('evaluation_ml_cyto_binary.csv')
binary_cyto_ptfm = pd.read_csv('evaluation_ptfm_binary_cyto.csv')

cyto_regression_overall_result = pd.concat([
    overall_cyto_claude,
    overall_cyto_gpt6,
    overall_cyto_grok,
    overall_cyto_ml,
    overall_cyto_ptfm
], ignore_index=True)

cyto_regression_overall_result = cyto_regression_overall_result.sort_values(by="Model").reset_index(drop=True)

cyto_regression_quantile_result = pd.concat([
    quantile_cyto_claude,
    quantile_cyto_gpt6,
    quantile_cyto_grok,
    quantile_cyto_ml,
    quantile_cyto_ptfm
], ignore_index=True)

cyto_regression_quantile_result = cyto_regression_quantile_result.sort_values(
    by="Model",
    ascending=True
).reset_index(drop=True)

cyto_binary_result = pd.concat([
    binary_cyto_claude,
    binary_cyto_gpt6,
    binary_cyto_grok,
    binary_cyto_ml,
    binary_cyto_ptfm
], ignore_index=True)

if 'F1' in cyto_binary_result.columns and 'F1-score' in cyto_binary_result.columns:
    cyto_binary_result['F1-score'] = cyto_binary_result['F1-score'].fillna(cyto_binary_result['F1'])
    cyto_binary_result = cyto_binary_result.drop(columns=['F1'])

cyto_binary_result = cyto_binary_result.sort_values(by="Model").reset_index(drop=True)

df_plot = cyto_regression_overall_result.sort_values(by="MAE", ascending=True)

fig = go.Figure()

# Add MAE horizontal bar
fig.add_trace(go.Bar(
    y=df_plot['Model'],
    x=df_plot['MAE'],
    name='MAE',
    orientation='h',
    marker=dict(color='royalblue')
))

# Add RMSE horizontal bar
fig.add_trace(go.Bar(
    y=df_plot['Model'],
    x=df_plot['RMSE'],
    name='RMSE',
    orientation='h',
    marker=dict(color='crimson')
))

# Configure chart layout
fig.update_layout(
    title="Overall MAE and RMSE Comparison Across Models (Cytotox)",
    xaxis_title="Error Metric Value (Lower is Better)",
    yaxis_title="Model",
    barmode='group',
    legend=dict(title="Metric"),
    height=600,
    margin=dict(l=150, r=20, t=80, b=50)
)

fig.show()

# Sort the overall regression dataset by R2 in descending order (best performance at the top)
df_r2_plot = cyto_regression_overall_result.sort_values(by="R2", ascending=True)

fig_r2 = go.Figure()

# Add R2 horizontal bar
fig_r2.add_trace(go.Bar(
    y=df_r2_plot['Model'],
    x=df_r2_plot['R2'],
    name='R-squared (R2)',
    orientation='h',
    marker=dict(color='Blue')
))

# Configure chart layout
fig_r2.update_layout(
    title="Overall R-squared (R2) Comparison Across Models (Cytotox)",
    xaxis_title="R-squared Value (Higher is Better)",
    yaxis_title="Model",
    height=600,
    margin=dict(l=150, r=40, t=80, b=50)
)

# Display the plot
fig_r2.show()

# Standardize quantile names to make filtering reliable
cyto_regression_quantile_result['Quantile_Clean'] = cyto_regression_quantile_result['Quantile'].str.extract(r'(Q\d)')
quantiles = ['Q1', 'Q2', 'Q3', 'Q4']

# Create a 2x2 subplot layout
fig = make_subplots(
    rows=2, cols=2,
    subplot_titles=[
        "Quantile 1 (0-25% Viability)",
        "Quantile 2 (25-50% Viability)",
        "Quantile 3 (50-75% Viability)",
        "Quantile 4 (75-100% Viability)"
    ],
    horizontal_spacing=0.15,
    vertical_spacing=0.12
)

# Keep track of colors and legend additions
colors = {'MAE': 'royalblue', 'RMSE': 'crimson'}
legend_added = {'MAE': False, 'RMSE': False}

for idx, q in enumerate(quantiles):
    # Filter data for current quantile and sort by MAE ascending
    df_q = cyto_regression_quantile_result[cyto_regression_quantile_result['Quantile_Clean'] == q].copy()
    df_q = df_q.sort_values(by="MAE", ascending=True)

    row = (idx // 2) + 1
    col = (idx % 2) + 1

    # Add MAE bar
    fig.add_trace(go.Bar(
        y=df_q['Model'],
        x=df_q['MAE'],
        name='MAE',
        orientation='h',
        marker=dict(color=colors['MAE']),
        showlegend=not legend_added['MAE'],
        legendgroup='MAE'
    ), row=row, col=col)
    legend_added['MAE'] = True

    # Add RMSE bar
    fig.add_trace(go.Bar(
        y=df_q['Model'],
        x=df_q['RMSE'],
        name='RMSE',
        orientation='h',
        marker=dict(color=colors['RMSE']),
        showlegend=not legend_added['RMSE'],
        legendgroup='RMSE'
    ), row=row, col=col)
    legend_added['RMSE'] = True

# Configure global layout settings
fig.update_layout(
    title="MAE and RMSE Comparison Across Quantiles (Cytotox)",
    barmode='group',
    height=900,
    width=1200,
    legend=dict(title="Metric", orientation="h", yanchor="bottom", y=1.02, xanchor="right", x=1),
    margin=dict(l=150, r=40, t=120, b=50)
)

# Add axis label configuration
fig.update_xaxes(title_text="Error Value (Lower is Better)")
fig.update_yaxes(title_text="Model")

fig.show()

cyto_regression_quantile_result['Quantile_Clean'] = cyto_regression_quantile_result['Quantile'].str.extract(r'(Q\d)')
quantiles = ['Q1', 'Q2', 'Q3', 'Q4']

# Create a 2x2 subplot layout for R2 comparisons
fig_r2_q = make_subplots(
    rows=2, cols=2,
    subplot_titles=[
        "Quantile 1 (0-25% Viability)",
        "Quantile 2 (25-50% Viability)",
        "Quantile 3 (50-75% Viability)",
        "Quantile 4 (75-100% Viability)"
    ],
    horizontal_spacing=0.15,
    vertical_spacing=0.12
)

# Use a distinct color for R2
r2_color = 'blue'
legend_added = False

for idx, q in enumerate(quantiles):
    # Filter data for current quantile and sort by R2 ascending
    df_q = cyto_regression_quantile_result[cyto_regression_quantile_result['Quantile_Clean'] == q].copy()
    df_q = df_q.sort_values(by="R2", ascending=True)

    row = (idx // 2) + 1
    col = (idx % 2) + 1

    # Add R2 bar
    fig_r2_q.add_trace(go.Bar(
        y=df_q['Model'],
        x=df_q['R2'],
        name='R-squared (R2)',
        orientation='h',
        marker=dict(color=r2_color),
        showlegend=not legend_added,
        legendgroup='R2'
    ), row=row, col=col)
    legend_added = True

# Configure global layout settings
fig_r2_q.update_layout(
    title="R-squared (R2) Comparison Across Quantiles (Cytotox)",
    height=900,
    width=1200,
    legend=dict(title="Metric", orientation="h", yanchor="bottom", y=1.02, xanchor="right", x=1),
    margin=dict(l=150, r=40, t=120, b=50)
)

# Add axis label configuration
fig_r2_q.update_xaxes(title_text="R-squared Value (Higher is Better)")
fig_r2_q.update_yaxes(title_text="Model")

fig_r2_q.show()

# Sort the binary result dataset by Accuracy
df_binary_plot = cyto_binary_result.sort_values(by="Accuracy", ascending=True)

fig_binary = go.Figure()

# Add Accuracy bar
fig_binary.add_trace(go.Bar(
    y=df_binary_plot['Model'],
    x=df_binary_plot['Accuracy'],
    name='Accuracy',
    orientation='h',
    marker=dict(color='teal')
))

# Add ROC-AUC bar
fig_binary.add_trace(go.Bar(
    y=df_binary_plot['Model'],
    x=df_binary_plot['ROC-AUC'],
    name='ROC-AUC',
    orientation='h',
    marker=dict(color='darkorange')
))

# Configure chart layout
fig_binary.update_layout(
    title="Accuracy and ROC-AUC Comparison Across Models (Cytotox Binary Classification)",
    xaxis_title="Metric Value (Higher is Better)",
    yaxis_title="Model",
    barmode='group',
    legend=dict(title="Metric"),
    height=600,
    margin=dict(l=150, r=40, t=80, b=50)
)

# Display the plot
fig_binary.show()

fig_binary.write_html(
    "cytotox_binary_accuracy_roc_comparison.html",
    include_plotlyjs=True
)

fig.write_html(
    "cytotox_overall_comparison.html",
    include_plotlyjs=True
)

fig.write_html(
    "cytotox_quantile_comparison.html",
    include_plotlyjs=True
)

fig_r2.write_html(
    "cytotox_overall_r2_comparison.html",
    include_plotlyjs=True
)

fig_r2_q.write_html(
    "cytotox_quantile_r2_comparison.html",
    include_plotlyjs=True
)

# Export the consolidated DataFrames to CSV files
cyto_regression_overall_result.to_csv('cyto_regression_overall_result.csv', index=False)
cyto_regression_quantile_result.to_csv('cyto_regression_quantile_result.csv', index=False)
cyto_binary_result.to_csv('cyto_binary_result.csv', index=False)